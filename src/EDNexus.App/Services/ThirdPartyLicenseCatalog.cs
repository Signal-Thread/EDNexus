using System.Text.Json;

namespace EDNexus.App.Services;

/// <summary>One third-party component EDNexus ships or talks to, with the licence it is used under.</summary>
/// <param name="Kind">"package", "font", "native" or "data".</param>
/// <param name="License">SPDX expression, or a plain description for services that only have terms of use.</param>
public sealed record ThirdPartyLicense(
    string Kind, string Name, string? Version, string License, string? Url, string? Authors, string? Note)
{
    /// <summary>Only web links are ever opened: the catalog is data, not something to launch arbitrary URIs from.</summary>
    public string? SafeUrl =>
        Uri.TryCreate(Url, UriKind.Absolute, out var u) && (u.Scheme == Uri.UriSchemeHttps || u.Scheme == Uri.UriSchemeHttp)
            ? u.AbsoluteUri
            : null;

    public string Display => Version is { Length: > 0 } v ? $"{Name} {v}" : Name;
}

/// <summary>
/// The "Open Source Contributions" list, read from the embedded <c>third-party-licenses.json</c>. The
/// NuGet half is generated by <c>tools/Update-ThirdPartyLicenses.ps1</c>; fonts, native engines and
/// data services are maintained by hand. Parsing is defensive: a malformed entry is skipped, never fatal.
/// </summary>
public static class ThirdPartyLicenseCatalog
{
    public const string ResourceUri = "avares://EDNexus.App/Assets/third-party-licenses.json";

    public static IReadOnlyList<ThirdPartyLicense> LoadEmbedded()
    {
        try
        {
            using var stream = Avalonia.Platform.AssetLoader.Open(new Uri(ResourceUri));
            return Parse(stream);
        }
        catch
        {
            return [];
        }
    }

    public static IReadOnlyList<ThirdPartyLicense> Parse(Stream json)
    {
        using var doc = JsonDocument.Parse(json);
        if (doc.RootElement.ValueKind != JsonValueKind.Object
            || !doc.RootElement.TryGetProperty("entries", out var entries)
            || entries.ValueKind != JsonValueKind.Array)
            return [];

        var list = new List<ThirdPartyLicense>();
        foreach (var e in entries.EnumerateArray())
        {
            if (e.ValueKind != JsonValueKind.Object) continue;
            var name = Str(e, "name");
            var license = Str(e, "license");
            if (string.IsNullOrWhiteSpace(name) || string.IsNullOrWhiteSpace(license)) continue;
            list.Add(new ThirdPartyLicense(
                Str(e, "kind") ?? "package", name, Str(e, "version"), license,
                Str(e, "url"), Str(e, "authors"), Str(e, "note")));
        }

        return list
            .OrderBy(l => KindOrder(l.Kind))
            .ThenBy(l => l.Name, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    private static int KindOrder(string kind) => kind switch { "data" => 0, "package" => 1, "font" => 2, "native" => 3, _ => 4 };

    private static string? Str(JsonElement e, string prop) =>
        e.TryGetProperty(prop, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() : null;
}
